"""Render the per-resource reachability/citation table from .scratch/eval/sample_eval.json.

    python code/evaluation/evaluate.py            # writes .scratch/eval/sample_eval.json
    python code/evaluation/render_reachability.py # writes code/evaluation/phase2_reachability.md
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))


def main():
    with open(os.path.join(REPO, ".scratch", "eval", "sample_eval.json"), encoding="utf-8") as f:
        j = json.load(f)
    rr = j["reach_rows"]
    key = lambda r: (r["case_id"], r["resource_id"])
    audit = {key(r): r for r in rr["audit"]["rows"]}
    oracle = {key(r): r for r in rr["oracle_resources"]["rows"]}
    cause = {key(m): m["cause"] for m in j["missing"]}
    out = ["# Sample reachability and citation agreement (per gold resource)", "",
           "Generated by `code/evaluation/render_reachability.py` from the sample evaluation. "
           "`audit` = identity links from captures at or before audit_at only; `any` = identity links from any "
           "capture (the default); `oracle` = our state engine's citation when handed the gold resource. "
           "Gold evidence is shown only where the public sample answer cites one.", ""]
    for name in ("audit", "any", "oracle_resources"):
        s = rr[name]
        out.append(f"- **{name}**: reached {s['reached']}/{s['total']}, citation agreement {s['cited_ok']}/{s['cited_total']}")
    out += ["", "| case | resource | gold ev | audit | any | our ev (any) | oracle ev | cause if unreached |",
            "|---|---|---|---|---|---|---|---|"]
    for r in rr["any"]["rows"]:
        k = key(r)
        a, o = audit.get(k, {}), oracle.get(k, {})
        mark = lambda x: "yes" if x.get("reached") else "no"
        # oracle rows list only disagreements; every other cited gold resource agrees
        orc = o.get("ours") or ("agrees" if r["gold_evidence"] else "-")
        out.append(f"| {r['case_id']} | {r['resource_id']} | {r['gold_evidence'] or '-'} | {mark(a)} | {mark(r)} | "
                   f"{r['our_evidence'] or '-'} | {orc} | {cause.get(k, '')} |")
    path = os.path.join(HERE, "phase2_reachability.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {path} ({len(rr['any']['rows'])} rows)")


if __name__ == "__main__":
    main()
